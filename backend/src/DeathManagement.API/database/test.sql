-- 1. Xác nhận database đang truy vấn
SELECT
    @@SERVERNAME AS TenServer,
    DB_NAME() AS TenDatabase;

-- 2. Liệt kê tất cả bảng thực tế
SELECT
    TABLE_SCHEMA,
    TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_NAME;

-- 3. Tìm các bảng liên quan đến ảnh
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    CHARACTER_MAXIMUM_LENGTH
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME LIKE '%HinhAnh%'
   OR TABLE_NAME LIKE '%Image%'
ORDER BY TABLE_NAME, ORDINAL_POSITION;